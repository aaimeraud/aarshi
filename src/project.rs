use std::{fs, path::Path};

use anyhow::{Context, Result, bail};

/// Create a file that must not exist yet, with its parent folders.
pub fn create_file(path: &Path, content: &str) -> Result<()> {
    if path.exists() {
        bail!("{} already exists", path.display());
    }
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)
            .with_context(|| format!("cannot create {}", parent.display()))?;
    }
    fs::write(path, content).with_context(|| format!("cannot write {}", path.display()))
}

pub fn read_file(path: &Path) -> Result<String> {
    fs::read_to_string(path).with_context(|| format!("cannot read {}", path.display()))
}

pub fn update_file(path: &Path, transform: impl FnOnce(&str) -> Result<String>) -> Result<()> {
    let content = read_file(path)?;
    let updated = transform(&content)?;
    fs::write(path, updated).with_context(|| format!("cannot write {}", path.display()))
}

/// Insert `line` above the line holding `marker`, using the marker's indentation.
pub fn insert_before_marker(content: &str, marker: &str, line: &str) -> Result<String> {
    let mut result = String::with_capacity(content.len() + line.len() + 1);
    let mut inserted = false;
    for current in content.split_inclusive('\n') {
        if !inserted && current.contains(marker) {
            let indent: String = current.chars().take_while(|c| c.is_whitespace()).collect();
            result.push_str(&indent);
            result.push_str(line);
            result.push('\n');
            inserted = true;
        }
        result.push_str(current);
    }
    if !inserted {
        bail!("marker `{marker}` not found; was this file generated by aarshi?");
    }
    Ok(result)
}

pub fn to_pascal_case(name: &str) -> String {
    name.split('-')
        .map(|part| {
            let mut chars = part.chars();
            match chars.next() {
                Some(first) => first.to_ascii_uppercase().to_string() + chars.as_str(),
                None => String::new(),
            }
        })
        .collect()
}

pub fn validate_name(kind: &str, name: &str) -> Result<()> {
    let mut chars = name.chars();
    let valid = matches!(chars.next(), Some(c) if c.is_ascii_lowercase())
        && chars.all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-');
    if !valid {
        bail!("invalid {kind} name `{name}` (use lowercase letters, digits and dashes)");
    }
    Ok(())
}
